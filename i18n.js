  function getLang(){
    try{ return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'pt'; }catch(e){ return 'pt'; }
  }
  function setLang(lang){
    try{ localStorage.setItem(LANG_KEY, lang); }catch(e){}
    location.reload();
  }
  window.KL_LANG = getLang();
  window.KL_T = function(key){
    if(window.KL_LANG !== 'en') return null;
    return Object.prototype.hasOwnProperty.call(EN, key) ? EN[key] : null;
  };

  function applyStaticI18n(){
    if(window.KL_LANG !== 'en') return;
    document.documentElement.lang = 'en';
    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var v = window.KL_T(el.getAttribute('data-i18n'));
      if(v !== null) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function(el){
      var v = window.KL_T(el.getAttribute('data-i18n-ph'));
      if(v !== null) el.setAttribute('placeholder', v);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function(el){
      var v = window.KL_T(el.getAttribute('data-i18n-title'));
      if(v !== null) el.setAttribute('title', v);
    });
    // Ligações da navegação — mesmo markup em todas as páginas, por isso
    // traduz-se por href em vez de precisar de data-i18n em cada ficheiro.
    var navMap = {
      'index.html': 'nav.home', 'torneios.html': 'nav.tournaments', 'criar-torneio.html': 'nav.create',
      'faq.html': 'nav.faq', 'contacto.html': 'nav.contact', 'login.html': 'nav.login'
    };
    document.querySelectorAll('nav .nav-links > li > a').forEach(function(a){
      var href = a.getAttribute('href');
      var key = navMap[href];
      if(key){ var v = window.KL_T(key); if(v !== null) a.textContent = v; }
    });
  }

  function injectToggle(){
    var nav = document.querySelector('nav');
    if(!nav || document.getElementById('kl-lang-toggle')) return;
    var wrap = document.createElement('div');
    wrap.id = 'kl-lang-toggle';
    wrap.className = 'nav-lang-toggle';
    var lang = window.KL_LANG;
    wrap.innerHTML =
      '<button type="button" data-lang="pt" class="' + (lang==='pt'?'active':'') + '">PT</button>' +
      '<button type="button" data-lang="en" class="' + (lang==='en'?'active':'') + '">EN</button>';
    nav.appendChild(wrap);
    wrap.querySelectorAll('button').forEach(function(btn){
      btn.addEventListener('click', function(){ setLang(btn.getAttribute('data-lang')); });
    });
  }

  document.addEventListener('DOMContentLoaded', function(){
    applyStaticI18n();
    injectToggle();
  });
